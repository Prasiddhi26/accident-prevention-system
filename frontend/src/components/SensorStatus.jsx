import { Satellite, Move3D, RotateCw, Camera } from 'lucide-react';

export default function SensorStatus({ data }) {
  const live = data.source === 'hardware';
  const label = live ? 'LIVE' : 'SIMULATED';
  const sensors = [
    { name: 'GPS', icon: Satellite, reading: `${data.speed} km/h` },
    { name: 'Accelerometer', icon: Move3D, reading: `${data.acceleration} m/s²` },
    { name: 'Gyroscope', icon: RotateCw, reading: `${data.gyroscope}°` },
    { name: 'Camera', icon: Camera, reading: 'No feed' },
  ];
  return (
    <section className="rounded-2xl border border-slate-800 bg-slate-900 p-5">
      <h2 className="text-lg font-semibold">Sensor Status</h2>
      <ul className="mt-4 space-y-3">
        {sensors.map(({ name, icon: Icon, reading }) => (
          <li key={name} className="flex items-center justify-between rounded-xl bg-slate-800/60 px-3 py-2.5">
            <span className="flex items-center gap-2 text-sm"><Icon size={16} className="text-slate-400" />{name}</span>
            <span className="flex items-center gap-2 text-xs">
              <span className="tabular-nums text-slate-400">{reading}</span>
              <span className="flex items-center gap-1.5 font-semibold text-emerald-400">
                <span className="h-2 w-2 rounded-full bg-emerald-400" />{label}
              </span>
            </span>
          </li>
        ))}
      </ul>
      <p className="mt-3 text-xs text-slate-500">
        {live ? 'Receiving data from a connected device.' : 'Hardware is not connected yet. All values are generated by the simulation.'}
      </p>
    </section>
  );
}
